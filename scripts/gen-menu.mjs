// Reads design/data/menu.js (which sets window.SC_MENU) and writes src/data/menu.json.
// Run: node scripts/gen-menu.mjs  (also runs before dev/build)
import fs from "node:fs";
import vm from "node:vm";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { assignSlugs } from "./slug.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const src = fs.readFileSync(path.join(root, "design/data/menu.js"), "utf8");
const ctx = { window: {} };
vm.runInNewContext(src, ctx);
const M = ctx.window.SC_MENU;
if (!M || !Array.isArray(M.items)) throw new Error("design/data/menu.js did not set window.SC_MENU");
/* the address of a dish of the main menu (decision 12.11.2026): the id stays, `slug` is the page address. Written only
   where it differs from the id (the menu chunk stays small); everywhere else the address is the id. Lunch items have no
   page of their own (they link to /obedno-menu/). The key goes right after the id. */
const slugs = assignSlugs(M.items);
M.items = M.items.map((x) => { const { id, slug: _old, ...rest } = x; const s = slugs.get(id); return s !== id ? { id, slug: s, ...rest } : { id, ...rest }; });
const out = path.join(root, "src/data/menu.json");
const json = JSON.stringify(M, null, 1) + "\n";
if (!fs.existsSync(out) || fs.readFileSync(out, "utf8") !== json) fs.writeFileSync(out, json);
/* the lunch menu's date as a tiny module, so the shared runtime knows "today" without the menu (src/lib/lunch-date.ts) */
const ld = path.join(root, "src/lib/lunch-date.ts");
const ldBody = "/* Generated by scripts/gen-menu.mjs from design/data/menu.js. Do not edit by hand. */\nexport const LUNCH_DATE = " + JSON.stringify(M.lunch.date) + ";\nexport const LUNCH_DAY_NAME = " + JSON.stringify(M.lunch.dayName || "") + ";\n";
if (!fs.existsSync(ld) || fs.readFileSync(ld, "utf8") !== ldBody) fs.writeFileSync(ld, ldBody);
const moved = M.items.filter((x) => x.slug).length;
console.log(`menu.json: ${M.cats.length} categories, ${M.items.length} items (${moved} with a new address), lunch ${M.lunch.date}`);
