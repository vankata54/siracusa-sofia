// Reads design/ds/icons.js (window.SC_ICONS, Phosphor 2.1.1, MIT) and writes:
//   src/lib/icons/<name>.ts   one module per icon; importing it registers the icon (only what a page imports is bundled)
//   src/lib/icons-all.ts      the full set (server rendering and lazy SC.icons() in the browser)
// The registry itself (ic(), registerIcons) is hand-written in src/lib/icons.ts. Run: node scripts/gen-icons.mjs
import fs from "node:fs";
import vm from "node:vm";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ctx = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(root, "design/ds/icons.js"), "utf8"), ctx);
const I = ctx.window.SC_ICONS;
const head = "/* Generated by scripts/gen-icons.mjs from design/ds/icons.js. Do not edit by hand. Phosphor Icons 2.1.1 (MIT). */\n";
const write = (f, body) => { if (!fs.existsSync(f) || fs.readFileSync(f, "utf8") !== body) fs.writeFileSync(f, body); };
const dir = path.join(root, "src/lib/icons");
fs.mkdirSync(dir, { recursive: true });
for (const [n, svg] of Object.entries(I))
  write(path.join(dir, n + ".ts"), head + 'import { registerIcons } from "../icons.ts";\nregisterIcons({ ' + JSON.stringify(n) + ": " + JSON.stringify(svg) + " });\n");
write(path.join(root, "src/lib/icons-all.ts"), head + 'import { registerIcons } from "./icons.ts";\nexport const ALL_ICONS: Record<string, string> = ' + JSON.stringify(I) + ";\nregisterIcons(ALL_ICONS);\n");
console.log(`icons: ${Object.keys(I).length} modules in src/lib/icons/ + icons-all.ts`);
