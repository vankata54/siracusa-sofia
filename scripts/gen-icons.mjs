// Reads design/ds/icons.js (window.SC_ICONS, Phosphor 2.1.1, MIT) and writes src/lib/icons.ts.
// All icons are kept (about 65 KB raw, but only used ones end up in the HTML; the client bundle
// imports the map once). Run: node scripts/gen-icons.mjs
import fs from "node:fs";
import vm from "node:vm";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ctx = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(root, "design/ds/icons.js"), "utf8"), ctx);
const I = ctx.window.SC_ICONS;
const body = "/* Generated by scripts/gen-icons.mjs from design/ds/icons.js. Do not edit by hand.\n   Phosphor Icons 2.1.1 (MIT), regular weight; plus/minus/check/x bold. */\n" +
  "export const ICONS: Record<string, string> = " + JSON.stringify(I) + ";\n";
const out = path.join(root, "src/lib/icons.ts");
if (!fs.existsSync(out) || fs.readFileSync(out, "utf8") !== body) fs.writeFileSync(out, body);
console.log(`icons.ts: ${Object.keys(I).length} icons`);
