// Builds design/ds/search.js (window.SCSearch) from src/lib/search.ts + src/lib/lexicon.ts, so the prototype searches
// exactly like the site (decision 15.11.2026: one search for the site, the table, the staff and the assistant).
// Run: node scripts/gen-proto-search.mjs  (after any change in src/lib/search.ts or src/lib/lexicon.ts)
import { build } from "esbuild";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
await build({
  entryPoints: [path.join(root, "src/lib/search.ts")], bundle: true, format: "iife", globalName: "SCSearch", target: "es2019",
  outfile: path.join(root, "design/ds/search.js"), charset: "utf8", legalComments: "none",
  banner: { js: "/* Generated by scripts/gen-proto-search.mjs from src/lib/search.ts and src/lib/lexicon.ts. Do not edit by hand.\n   window.SCSearch: searchDishes(list, q) -> {name, comp, band, rest, unknown, query}, chips(q), toggle(q, word), parse(q), latin(s). */" },
});
console.log("design/ds/search.js");
